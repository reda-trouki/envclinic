import { scanProject } from "../../core/auditor";
import { buildTypesContent, typesOutputPath } from "../../core/outputs";
import { loadProject } from "../../core/project";
import { GENERATED_MARKER } from "../../core/type-generator";
import {
  readExisting,
  resolveWriteTarget,
  writeProjectFile,
} from "../../core/writer";
import type { IO } from "../io";
import { note, toAuditOptions, UsageError, type CliOptions } from "./common";

/** Generate TypeScript declarations (names and types only, never values). */
export async function typesCommand(
  options: CliOptions,
  io: IO,
): Promise<number> {
  const project = await loadProject(toAuditOptions(options, []));
  const usage =
    options.scan === false
      ? undefined
      : (await scanProject(project, { secrets: false })).usage;
  const content = buildTypesContent(project, usage);

  const output = typesOutputPath(project, options.output);
  const target = await resolveWriteTarget(project.cwd, output);
  if (!target.ok)
    throw new UsageError(`Cannot write ${output}: ${target.reason}.`);
  const existing = await readExisting(target.absolute);

  if (options.check) {
    if (existing === undefined) {
      note(
        io,
        options,
        `${output} does not exist. Run \`envclinic types\` to generate it.`,
      );
      return 1;
    }
    if (existing.replace(/\r\n/g, "\n") !== content) {
      note(
        io,
        options,
        `${output} is out of date. Run \`envclinic types\` to regenerate it.`,
      );
      return 1;
    }
    note(io, options, `${output} is up to date.`);
    return 0;
  }

  if (
    existing !== undefined &&
    !options.force &&
    !existing.trimStart().startsWith(GENERATED_MARKER)
  ) {
    throw new UsageError(
      `${output} was not generated by envclinic, so it will not be overwritten. Use --output to pick another path or --force to replace it.`,
    );
  }

  if (options.dryRun) {
    io.out(content);
    io.err(`Dry run: ${output} was not written.\n`);
    return 0;
  }

  const written = await writeProjectFile(project.cwd, output, content, {
    overwrite: true,
  });
  if (written.status === "refused")
    throw new UsageError(`Could not write ${output}: ${written.reason}.`);
  note(
    io,
    options,
    written.status === "unchanged"
      ? `${output} is already up to date.`
      : `Wrote ${output}.`,
  );
  return 0;
}
